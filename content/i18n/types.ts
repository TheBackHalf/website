import type { Locale } from "@/lib/i18n/config";

export type PendingTranslation = {
  pending: true;
  fallback?: string;
};

export type TranslatedString = string | PendingTranslation;

export function isTranslationPending(
  value: TranslatedString,
): value is PendingTranslation {
  return typeof value === "object" && value.pending === true;
}

export function resolveTranslation(value: TranslatedString, locale: Locale): string {
  if (!isTranslationPending(value)) {
    return value;
  }

  if (locale === "en") {
    return value.fallback ?? "";
  }

  return "";
}

